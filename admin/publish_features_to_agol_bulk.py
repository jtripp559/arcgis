"""
================================================================================
Script Name  : publish_features_to_agol_bulk.py
Description  : To publish feature layers in ArcGIS Online (AGOL)
               getting the information from RRG NBS ArcGIS Enterprise Portal
               by registering each layer as a proxied item using
               stored-credential authentication (serviceUsername/servicePassword).

               Workflow:
                 1. Authenticates to AGOL via direct login.
                 2. Reads a pre-built layer_list generated by
                    `extract_featureLayer_metadata_from_ArcGIS_portal.py`.
                 3. Creates the target folder in AGOL if it does not exist.
                 4. Locates the target sharing group by search term.
                 5. For each layer: adds the proxied item to root, moves it to
                    the target folder, and shares it with the org and group.

Usage        : Run interactively in an ArcGIS Pro Jupyter Notebook or python shell
               within ArcGIS Pro session.
               Requires an active internet connection and valid AGOL credentials.

Inputs       : layer_list  - Python list of dicts produced by
                            `extract_featureLayer_metadata_from_ArcGIS_portal.py`
                             Each dict contains: title, url, snippet, description.
               GP_USER / GP_PASS - Stored credentials for the Enterprise Portal
                             used to authenticate the proxied service connections.

Outputs      : Proxied Feature/Image Service items published to AGOL under spe=cified
               folder and group, e.g.:
               folder  : RRGNBS Cacao Suitability
               group   : RRG AGO Organization Datashare

Dependencies : arcgis (ArcGIS API for Python), getpass
               Valid AGOL account (user name @ rrg.maps.arcgis.com)
               Valid Enterprise Portal credentials for maps.rrgnbs.com

Notes        : - Items are added to root first then moved to avoid a known
                 NoneType folder in the ArcGIS API for Python.
               - GP_USER / GP_PASS are embedded as plain text; REMOVE password
               from Script.

Author       : guillermo.ponce@rrgnbs.com
Created      : 2026-03-26
Last Modified: 2026-03-26
================================================================================
"""

from arcgis.gis import GIS
import getpass

# 1. DIRECT LOGIN
print("Enter your password for the AGOL Cloud (guillermo.ponce_nbs):")
agol_pass = getpass.getpass()

print("\nConnecting directly to AGOL with full privileges...")
gis = GIS("https://rrg.maps.arcgis.com", "guillermo.ponce_nbs", agol_pass)

# 2. Configuration to enable the option `Store Credentials`
GP_USER = "GPUser"
GP_PASS = (
    "xxxxxx"  # Check it in Keeper account and don't forget to remove it from here.
)

# Set folder and groups
CLOUD_FOLDER_NAME = "RRGNBS Cacao Suitability"
GROUP_SEARCH_TERM = (
    "RRG AGO Organization Datashare"  ## Check the best group to use here
)

# 3. ############## PASTE LIST GENERATED WITH extract_featureLayer_metadata_from_ArcGIS_portal.py
layer_list = []

# 4. Create Folder Safely (Ignores if it already exists)
try:
    gis.content.create_folder(CLOUD_FOLDER_NAME)
    print(f"Verified folder: {CLOUD_FOLDER_NAME}")
except Exception:
    pass

# 5. Find Group
groups = gis.groups.search(GROUP_SEARCH_TERM)
target_group = groups[0] if groups else None
if not target_group:
    print(
        f"Could not find group '{GROUP_SEARCH_TERM}'. Will create items without sharing."
    )
else:
    print(f"Found target group: {target_group.title}")

# 6. Migration Loop
print(f"\nStarting migration of {len(layer_list)} layers...")

for item in layer_list:
    try:
        print(f"Checking item: {item['title']}...")

        service_type = (
            "Feature Service" if "FeatureServer" in item["url"] else "Image Service"
        )

        # Everything in str()
        props = {
            "title": str(item["title"]),
            "type": str(service_type),
            "url": str(item["url"]),
            "snippet": str(item.get("snippet", "Cacao Suitability Change Analysis.")),
            "description": str(
                item.get("description", "Metadata for Cacao Climate Suitability.")
            ),
            "tags": "Cacao, MaxEnt, Climate Suitability, RRGNBS",
            "serviceUsername": str(GP_USER),
            "servicePassword": str(GP_PASS),
        }

        # STEP 1: Add to Root
        new_proxy = gis.content.add(item_properties=props)

        # STEP 2: Move to Folder
        new_proxy.move(CLOUD_FOLDER_NAME)

        # STEP 3: Share
        if target_group:
            new_proxy.share(org=True, groups=[target_group.id])
            print(f"Success & Shared: {item['title']}")
        else:
            print(f"Success (Moved to folder, not shared): {item['title']}")

    except Exception as e:
        print(f"Failed {item['title']}: {e}")

print("\n--- **** PUBLISHING COMPLETE **** ---")
