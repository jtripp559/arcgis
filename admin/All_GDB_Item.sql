SELECT GDB_ITEMTYPES.Name AS ItemType_Name,
      GDB_ITEMS.Name,
      GDB_ITEMS.ObjectID,
      GDB_ITEMS.UUID,
      -- GDB_ITEMS.Type,
      GDB_ITEMS.PhysicalName,
      GDB_ITEMS.Path,
      -- GDB_ITEMS.Url,
      -- GDB_ITEMS.Properties,
      -- GDB_ITEMS.Defaults,
      --GDB_ITEMS.DatasetSubtype1,
      --GDB_ITEMS.DatasetSubtype2,
      GDB_ITEMS.DatasetInfo1,
      GDB_ITEMS.Shape,
      --GDB_ITEMS.DatasetInfo2,
      --GDB_ITEMS.ContingentValues,
      GDB_ITEMS.Definition,
      GDB_ITEMS.Documentation,
      GDB_ITEMS.ItemInfo,
( SELECT GDB_ITEMRELATIONSHIPTYPES.Name AS RelationshipType,
        RELATED_ITEM.ObjectID AS ItemObjectID,
        RELATED_ITEM.UUID AS ItemUUID,
        RELATED_ITEM.Name AS ItemName,
        RELATED_ITEM_TYPE.Name AS ItemType
FROM GDB_ITEMRELATIONSHIPS
LEFT JOIN GDB_ITEMRELATIONSHIPTYPES ON GDB_ITEMRELATIONSHIPTYPES.UUID = GDB_ITEMRELATIONSHIPS.TYPE
LEFT JOIN GDB_ITEMS AS RELATED_ITEM ON RELATED_ITEM.UUID = GDB_ITEMRELATIONSHIPS.DestID
LEFT JOIN GDB_ITEMTYPES AS RELATED_ITEM_TYPE ON RELATED_ITEM_TYPE.UUID = RELATED_ITEM.TYPE
WHERE GDB_ITEMRELATIONSHIPS.OriginID = GDB_ITEMS.UUID
ORDER BY GDB_ITEMRELATIONSHIPTYPES.Name,
      RELATED_ITEM_TYPE.Name,
			RELATED_ITEM.ObjectID
FOR XML PATH('Relationship'), ROOT('Relationships') ) AS ChildRelationships,
( SELECT GDB_ITEMRELATIONSHIPTYPES.Name AS RelationshipType,
        RELATED_ITEM.ObjectID AS ItemObjectID,
        RELATED_ITEM.UUID AS ItemUUID,
        RELATED_ITEM.Name AS ItemName,
        RELATED_ITEM_TYPE.Name AS ItemType
FROM GDB_ITEMRELATIONSHIPS
LEFT JOIN GDB_ITEMRELATIONSHIPTYPES ON GDB_ITEMRELATIONSHIPTYPES.UUID = GDB_ITEMRELATIONSHIPS.TYPE
LEFT JOIN GDB_ITEMS AS RELATED_ITEM ON RELATED_ITEM.UUID = GDB_ITEMRELATIONSHIPS.OriginID
LEFT JOIN GDB_ITEMTYPES AS RELATED_ITEM_TYPE ON RELATED_ITEM_TYPE.UUID = RELATED_ITEM.TYPE
WHERE GDB_ITEMRELATIONSHIPS.DestID = GDB_ITEMS.UUID
ORDER BY GDB_ITEMRELATIONSHIPTYPES.Name,
      RELATED_ITEM_TYPE.Name,
			RELATED_ITEM.ObjectID
FOR XML PATH('Relationship'), ROOT('Relationships') ) AS ParentRelationships

  FROM GDB_ITEMS
LEFT JOIN GDB_ITEMTYPES ON GDB_ITEMTYPES.UUID = GDB_ITEMS.TYPE
ORDER BY GDB_ITEMTYPES.Name,
			GDB_ITEMS.ObjectID;